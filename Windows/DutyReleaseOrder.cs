    // Same normalization as the website's dutyReleaseOrder(): strip a
    // trailing difficulty suffix, capitalize a lowercased leading article,
    // and normalize dash variants — all differences between how the game
    // renders a duty name and how the underlying sheet/website data stores it.
    public static int? For(string dutyName)
    {
        if (string.IsNullOrEmpty(dutyName))
            return null;

        var baseName = Regex.Replace(dutyName, @"\s*\((Extreme|Savage|Ultimate|Unreal|Chaotic|Hard)\)\s*$", "", RegexOptions.IgnoreCase).Trim();
        baseName = Regex.Replace(baseName, @"^(the|a|an)\s", m => char.ToUpperInvariant(m.Value[0]) + m.Value.Substring(1), RegexOptions.IgnoreCase);
        baseName = Regex.Replace(baseName, "[‐-―]", "-");

        return Table.TryGetValue(baseName, out var order) ? order : null;
    }
